def test_create_event_basic(media_root, events_singleton):
    start = timezone.now()
    end = start + timezone.timedelta(hours=2)

    event = Event.objects.create(
        title="Concert",
        description="Live music in the park",
        start_at=start,
        end_at=end,
        is_published=True,
    )

    assert event.pk is not None
    assert event.slug.startswith("concert")
    assert event.safe_translation_getter("title", any_language=True) == "Concert"
    assert event.end_at == end
    # Test backward compatibility properties
    assert event.created_at is not None
    assert event.updated_at is not None
    # Test auto-assigned category
    assert event.category == events_singleton.category


def test_end_before_start_raises_validation_error(media_root, events_singleton):
    start = timezone.now()
    end = start - timezone.timedelta(hours=1)

    with pytest.raises(ValidationError):
        Event.objects.create(
            title="Invalid",
            start_at=start,
            end_at=end,
        )


def test_slug_autogenerated_and_unique(media_root, events_singleton):
    start = timezone.now()
    event_one = Event.objects.create(title="Fiesta", start_at=start)
    event_two = Event.objects.create(title="Fiesta", start_at=start + timezone.timedelta(hours=1))

    assert event_one.slug == "fiesta"
    assert event_two.slug == "fiesta-2"


def test_is_future(media_root, events_singleton):
    future_event = Event.objects.create(
        title="Future Event",
        start_at=timezone.now() + timezone.timedelta(days=1),
    )
    past_event = Event.objects.create(
        title="Past Event",
        start_at=timezone.now() - timezone.timedelta(days=1),
    )

    assert future_event.is_future() is True
    assert past_event.is_future() is False


def test_event_can_attach_media(media_root, events_singleton, sample_document, sample_image):
    start = timezone.now() + timezone.timedelta(hours=3)

    event = Event.objects.create(
        title="Media Event",
        start_at=start,
        featured_media=sample_image,
    )
    event.attachments.add(sample_document)

    assert event.featured_media == sample_image
    assert event.attachments.count() == 1


def test_event_category_singleton(events_category):
    """Test that EventCategorySingleton works correctly."""
    singleton = EventCategorySingleton.objects.create(category=events_category)
    
    assert singleton.category == events_category
    assert EventCategorySingleton.get_default_category() == events_category
    
    # Test that get_solo() returns the same instance
    same_singleton = EventCategorySingleton.get_solo()
    assert same_singleton.pk == singleton.pk


def test_event_auto_assigns_category(events_singleton):
    """Test that events automatically get the default category."""
    event = Event.objects.create(
        title="Auto Category Test",
        start_at=timezone.now(),
    )
    
    assert event.category == events_singleton.category
