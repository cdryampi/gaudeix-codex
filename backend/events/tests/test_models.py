def test_delete_event_date_updates_cache(events_singleton):
    start1 = timezone.now() + timezone.timedelta(days=1)
    start2 = timezone.now() + timezone.timedelta(days=2)

    event = Event.objects.create(title="Festival")
    d1 = EventDate.objects.create(event=event, start_at=start1)
    d2 = EventDate.objects.create(event=event, start_at=start2)

    # Initial state: nearest date is d1
    event.refresh_from_db()
    assert event.start_at == start1

    # Delete d1
    d1.delete()

    # Cache should update to d2
    event.refresh_from_db()
    assert event.start_at == start2


def test_past_event_fallback(events_singleton):
    """If all dates are past, cache should show the last one"""
    past1 = timezone.now() - timezone.timedelta(days=10)
    past2 = timezone.now() - timezone.timedelta(days=5)

    event = Event.objects.create(title="Past Event")
    EventDate.objects.create(event=event, start_at=past1)
    EventDate.objects.create(event=event, start_at=past2)

    event.refresh_from_db()
    event.update_cached_dates()
    event.refresh_from_db()

    # Should be the latest past date (past2)
    assert event.start_at == past2
