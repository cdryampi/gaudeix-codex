def test_create_event_basic(media_root, events_singleton):
    event = Event.objects.create(
        title="Concert",
        summary="Short summary",
        description="Live music in the park",
        is_published=True,
    )

    assert event.pk is not None
    assert event.slug.startswith("concert")
    assert event.safe_translation_getter("title", any_language=True) == "Concert"
    assert event.category == events_singleton.category


def test_create_event_with_dates(media_root, events_singleton):
    event = Event.objects.create(title="Multi-date")
    start1 = timezone.now() + timezone.timedelta(days=1)
    start2 = timezone.now() + timezone.timedelta(days=2)

    d1 = EventDate.objects.create(event=event, start_at=start1)
    d2 = EventDate.objects.create(event=event, start_at=start2)

    assert event.dates.count() == 2

    # Check that Event.start_at was updated by signal
    event.refresh_from_db()
    assert event.start_at == start1


