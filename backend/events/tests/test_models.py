def test_is_future(media_root, events_singleton):
    future_event = Event.objects.create(title="Future")
    EventDate.objects.create(
        event=future_event, start_at=timezone.now() + timezone.timedelta(days=1)
    )

    past_event = Event.objects.create(title="Past")
    EventDate.objects.create(
        event=past_event, start_at=timezone.now() - timezone.timedelta(days=1)
    )

    assert future_event.is_future() is True
    assert past_event.is_future() is False


